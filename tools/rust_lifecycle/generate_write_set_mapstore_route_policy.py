def render_all(rows: list[list[str]]) -> dict[Path, str]:
    outputs = {
        GENERATED["rust"]: render(rows),
        GENERATED["i64_policy"]: render_classifier(row_by_route(rows, "MapStoreI64"), "MapStoreI64", "ScalarI64"),
        GENERATED["any_policy"]: render_classifier(row_by_route(rows, "MapStoreAny"), "MapStoreAny", "Any", "DeclaredMetadataOnly"),
        GENERATED["i64_caller"]: render_caller(row_by_route(rows, "MapStoreI64"), "MapStoreI64"),
        GENERATED["any_caller"]: render_caller(row_by_route(rows, "MapStoreAny"), "MapStoreAny"),
    }
    formatted: dict[Path, str] = {}
    for path, content in outputs.items():
        result = subprocess.run(
            ["rustfmt", "--edition", "2021", "--emit", "stdout"],
            input=content,
            text=True,
            capture_output=True,
            check=False,
        )
        if result.returncode != 0:
            raise SystemExit(f"rustfmt failed for {path.relative_to(ROOT)}: {result.stderr}")
        formatted[path] = result.stdout
    return formatted


def artifact_key(name: str) -> str:
    key = {
        "rust": "rust",
        "i64_policy": "i64_policy",
        "any_policy": "any_policy",
        "i64_caller": "i64_caller",
        "any_caller": "any_caller",
    }.get(name)
    if key is None:
        raise SystemExit(f"unknown MapStore artifact: {name}")
    return key


def check_outputs(outputs: dict[Path, str]) -> None:
    stale = [str(path.relative_to(ROOT)) for path, expected in outputs.items()
             if not path.exists() or path.read_text(encoding="utf-8") != expected]
    if stale:
        raise SystemExit("stale generated MapStore artifacts:\n" + "\n".join(stale))


def write_outputs(outputs: dict[Path, str]) -> None:
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(content)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp_name, path)
        except Exception:
            Path(tmp_name).unlink(missing_ok=True)
            raise


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Verify all generated artifacts.")
    mode.add_argument("--write", action="store_true", help="Write all generated artifacts atomically.")
    parser.add_argument("--artifact", choices=["rust", "i64_policy", "any_policy", "i64_caller", "any_caller"])
    args = parser.parse_args()
    outputs = render_all(read_rows(args.source))
    if args.check:
        check_outputs(outputs)
    elif args.write:
        write_outputs(outputs)
    elif args.artifact:
        print(outputs[GENERATED[artifact_key(args.artifact)]], end="")
    else:
        print(outputs[GENERATED["rust"]], end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
