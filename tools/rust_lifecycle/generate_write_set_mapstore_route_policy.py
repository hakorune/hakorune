import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "lang/src/compiler/lib/write_set_mapstore_route_policy.hako"
EXPECTED = {
    "MapStoreI64": ("map_store_i64_set_surface", "I64", "Any"),
    "MapStoreAny": ("map_store_any_set_surface", "Any", "Any"),
}
GENERATED = {
    "rust": ROOT / "src/mir/generic_method_route_plan/generated/write_set_mapstore_route_policy.rs",
    "i64_policy": ROOT / "src/mir/generic_method_route_plan/generated/write_set_mapstore_i64_hako_policy.rs",
    "any_policy": ROOT / "src/mir/generic_method_route_plan/generated/write_set_mapstore_any_hako_policy.rs",
    "i64_caller": ROOT / "src/mir/generic_method_route_plan/generated/write_set_mapstore_i64_caller_orientation_contract.rs",
    "any_caller": ROOT / "src/mir/generic_method_route_plan/generated/write_set_mapstore_any_caller_orientation_contract.rs",
}


def read_rows(source: Path) -> list[list[str]]:
    rows: list[list[str]] = []
    for line in source.read_text(encoding="utf-8").splitlines():
        marker = '"map_store_'
        start = line.find(marker)
        if start < 0:
            continue
        raw = line[start + 1 : line.rfind('"')]
        fields = raw.split("|")
        if len(fields) != 13:
            raise SystemExit(f"MapStore RoutePolicyRow has {len(fields)} fields, expected 13")
        rows.append(fields)
    if len(rows) != len(EXPECTED):
        raise SystemExit(f"MapStore RoutePolicyRow count drift: {len(rows)}")
    return rows


def validate(fields: list[str]) -> None:
    (
        row_id,
        route_kind,
        key_domain,
        stored_value_domain,
        result_shape,
        effect_class,
        mutation_class,
        publication_policy,
        surface,
        core_op,
        lowering_tier,
        value_demand,
        authority_kind,
    ) = fields
    expected = EXPECTED.get(route_kind)
    if expected is None or expected[1:] != (key_domain, stored_value_domain):
        raise SystemExit(f"{route_kind} key/value domain drift: {fields!r}")
    if row_id != expected[0]:
        raise SystemExit(f"{route_kind} policy row identity drift: {row_id}")
    expected_fields = {
        "result_shape": "None",
        "effect_class": "mutate",
        "mutation_class": "MutatesReceiverOrContainer",
        "publication_policy": "NonePublication",
        "core_op": "MapSet",
        "lowering_tier": "ColdFallback",
        "value_demand": "WriteAny",
        "authority_kind": "HakoPolicyRow",
    }
    actual = locals()
    for name, value in expected_fields.items():
        if actual[name] != value:
            raise SystemExit(f"{route_kind} {name} drift: {actual[name]!r}")
    if not surface.startswith("SetSurfacePolicy"):
        raise SystemExit(f"{route_kind} surface drift: {surface!r}")


def lit(value: str) -> str:
    return json.dumps(value)


