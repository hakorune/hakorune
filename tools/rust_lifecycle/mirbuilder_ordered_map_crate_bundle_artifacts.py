def build_ordered_map_crate_bundle_hako_text() -> str:
    binding_spec = binding_context_spec()
    box_spec = box_compilation_context_spec()
    core_spec = core_context_spec()
    allocation_spec = prepared_state_kernel_spec()
    variable_spec = variable_context_simple_map_spec()
    snapshot_spec = variable_context_snapshot_restore_spec()
    binding_hako = build_family_artifact_hako_text(binding_spec)
    box_hako = build_family_artifact_hako_text(box_spec)
    core_hako = build_family_artifact_hako_text(core_spec)
    allocation_hako = build_family_artifact_hako_text(allocation_spec)
    variable_hako = build_family_artifact_hako_text(variable_spec)
    snapshot_hako = build_family_artifact_hako_text(snapshot_spec)

    binding_body = _extract_family_body_without_main(binding_hako, box_name=binding_spec.box.name, static_box_name=binding_spec.api_name)
    box_body = _extract_family_body_without_main(box_hako, box_name=box_spec.box.name, static_box_name=box_spec.api_name)
    core_body = _extract_family_body_without_main(core_hako, box_name=core_spec.box.name, static_box_name=core_spec.api_name)
    allocation_blocks = [
        _extract_box_block(allocation_hako, "FunctionValueIdCounterState"),
        _extract_box_block(allocation_hako, "ReservedValueIdMembershipView"),
        _extract_static_box_block(allocation_hako, "FunctionValueIdCounterStateApi"),
        _extract_static_box_block(allocation_hako, "ReservedValueIdMembershipViewApi"),
        _extract_static_box_block(allocation_hako, "MirBuilderAllocationPolicyApi"),
    ]
    variable_box = _extract_box_block(variable_hako, variable_spec.box.name)
    variable_api = _merge_static_box(
        variable_spec.api_name,
        _extract_static_box_methods(variable_hako, variable_spec.api_name),
        _extract_static_box_methods(snapshot_hako, snapshot_spec.api_name),
    )

    lines = _bundle_header()
    lines.extend(binding_body.splitlines())
    lines.append("")
    lines.extend(box_body.splitlines())
    lines.append("")
    lines.extend(core_body.splitlines())
    lines.append("")
    lines.extend("\n\n".join(allocation_blocks).splitlines())
    lines.append("")
    lines.extend(variable_box.splitlines())
    lines.append("")
    lines.extend(variable_api.splitlines())
    lines.append("")
    lines.append("static box Main {")
    lines.append("    main() {")
    lines.extend(indent([line for operation in _bundle_main_operations() for line in render_main_operation(operation)], 8))
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


