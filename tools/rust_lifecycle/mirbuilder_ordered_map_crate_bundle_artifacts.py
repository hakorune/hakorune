def _extract_balanced_block(hako_text: str, marker: str) -> str:
    start = hako_text.index(marker)
    depth = 0
    seen_open = False
    for offset, char in enumerate(hako_text[start:]):
        if char == "{":
            depth += 1
            seen_open = True
        elif char == "}":
            depth -= 1
            if seen_open and depth == 0:
                return hako_text[start : start + offset + 1].rstrip()
    raise ValueError(f"unterminated Hako block: {marker}")


def _extract_box_block(hako_text: str, box_name: str) -> str:
    return _extract_balanced_block(hako_text, f"box {box_name} {{")


def _extract_static_box_block(hako_text: str, static_box_name: str) -> str:
    return _extract_balanced_block(hako_text, f"static box {static_box_name} {{")


def _extract_static_box_methods(hako_text: str, static_box_name: str) -> list[str]:
    block = _extract_static_box_block(hako_text, static_box_name)
    lines = block.splitlines()
    if len(lines) < 2:
        raise ValueError(f"empty static box block: {static_box_name}")
    return lines[1:-1]


def _merge_static_box(static_box_name: str, *method_groups: list[str]) -> str:
    lines = [f"static box {static_box_name} {{"]
    for index, methods in enumerate(method_groups):
        if index:
            lines.append("")
        lines.extend(methods)
    lines.append("}")
    return "\n".join(lines)


def _extract_family_body_without_main(hako_text: str, *, box_name: str, static_box_name: str) -> str:
    return "\n\n".join(
        [
            _extract_box_block(hako_text, box_name),
            _extract_static_box_block(hako_text, static_box_name),
        ]
    )


